-- ---------------------------------------------------------------------------
-- 幂等创建 publication。
-- 使用 DO 块而不是 CREATE PUBLICATION IF NOT EXISTS（PG16 仍不支持该写法）。
-- 已存在时用 SET TABLE 校正表清单，保证重复执行后状态一致。
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'oa_publication') THEN
        CREATE PUBLICATION oa_publication FOR TABLE public.customers, public.orders;
    ELSE
        ALTER PUBLICATION oa_publication SET TABLE public.customers, public.orders;
    END IF;
END
$$;

-- 便于人工核对：逻辑复制参数 + publication 内容。
SELECT current_setting('wal_level') AS wal_level;
SELECT pubname, puballtables FROM pg_publication WHERE pubname = 'oa_publication';
SELECT pubname, schemaname, tablename
FROM pg_publication_tables
WHERE pubname = 'oa_publication'
ORDER BY schemaname, tablename;