-- 安全性：本文件只包含虚构的本地测试数据，不包含任何真实客户/生产数据、口令或连接信息。
-- 用途：作为 Debezium PostgreSQL source 的源表，验证逻辑复制、publication 与 Iceberg sink。
-- 执行时机：postgres 官方镜像仅在数据卷首次初始化时执行 /docker-entrypoint-initdb.d/*.sql；
-- 如需在已有卷上重跑，可手动 `psql -f 01_schema.sql`（本文件设计为幂等）。
--
-- 约束（与 design D1/D3、任务 5.2 对齐）：
--   * 两张有主键的表：public.customers、public.orders
--   * REPLICA IDENTITY FULL（记录 before/after 镜像，便于验证）
--   * 幂等创建 publication：oa_publication
--
-- 注意：design.md 测试策略里曾使用 demo schema；本文件按部署任务要求使用 public schema。

BEGIN;

-- ---------------------------------------------------------------------------
-- 表结构
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.customers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL UNIQUE,
    full_name   text        NOT NULL,
    country     text        NOT NULL DEFAULT 'CN',
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.orders (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint      NOT NULL REFERENCES public.customers (id),
    status       text        NOT NULL CHECK (status IN ('created', 'paid', 'shipped', 'cancelled')),
    total_cents  bigint      NOT NULL CHECK (total_cents >= 0),
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- 逻辑复制需要表具备 REPLICA IDENTITY FULL 才能拿到完整旧值（design 测试策略要求）。
ALTER TABLE public.customers REPLICA IDENTITY FULL;
ALTER TABLE public.orders    REPLICA IDENTITY FULL;

