#!/usr/bin/env bash
# delivery-images.sh — build core/web images, push to the local registry, record
# digests to dist/delivery/digests.env and pin them in deploy/releases/kind.yaml.
#
# Requires docker and a running local registry (see deploy/kind/kind-up.sh).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

REGISTRY="${IMAGE_REGISTRY:-localhost:5000}"
TAG="${IMAGE_TAG:-$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo dev)}"
RELEASE_FILE="${RELEASE_FILE:-$ROOT/deploy/releases/kind.yaml}"
OUT_DIR="$ROOT/dist/delivery"
COMMIT="${IMAGE_COMMIT:-$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo "")}"
OPERATOR="${OPERATOR:-local}"

log() { printf '\033[1;34m[%s]\033[0m %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "docker not found"
mkdir -p "$OUT_DIR"

CORE_IMAGE="${REGISTRY}/ontoaxis-core:${TAG}"
WEB_IMAGE="${REGISTRY}/ontoaxis-web:${TAG}"

log "building core image ${CORE_IMAGE}"
docker build -t "$CORE_IMAGE" -f "$ROOT/Dockerfile" "$ROOT"
log "building web image ${WEB_IMAGE}"
docker build -t "$WEB_IMAGE" -f "$ROOT/web/Dockerfile" "$ROOT"

log "pushing core image"
docker push "$CORE_IMAGE"
log "pushing web image"
docker push "$WEB_IMAGE"

core_digest="$(docker inspect --format '{{index .RepoDigests 0}}' "$CORE_IMAGE" 2>/dev/null | sed 's/.*@//')"
web_digest="$(docker inspect --format '{{index .RepoDigests 0}}' "$WEB_IMAGE" 2>/dev/null | sed 's/.*@//')"
case "$core_digest" in sha256:*) ;; *) die "core digest not a sha256 (got '${core_digest}')" ;; esac
case "$web_digest" in sha256:*) ;; *) die "web digest not a sha256 (got '${web_digest}')" ;; esac

{
  echo "# generated by delivery-images.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "IMAGE_REGISTRY=${REGISTRY}"
  echo "IMAGE_TAG=${TAG}"
  echo "IMAGE_COMMIT=${COMMIT}"
  echo "CORE_IMAGE=${CORE_IMAGE}"
  echo "CORE_DIGEST=${core_digest}"
  echo "WEB_IMAGE=${WEB_IMAGE}"
  echo "WEB_DIGEST=${web_digest}"
} >"$OUT_DIR/digests.env"
log "wrote $OUT_DIR/digests.env"

[ -f "$RELEASE_FILE" ] || die "release manifest not found: $RELEASE_FILE (create it from deploy/releases/kind.yaml template)"
python3 - "$RELEASE_FILE" "$REGISTRY" "$TAG" "$COMMIT" "$core_digest" "$web_digest" "$OPERATOR" <<'PY'
import sys, re, datetime
path, registry, tag, commit, core_digest, web_digest, operator = sys.argv[1:8]
now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
lines = open(path, encoding="utf-8").read().splitlines()
targets = {
    "ontoaxis-core": {"repository": f"{registry}/ontoaxis-core", "digest": core_digest, "commit": commit},
    "ontoaxis-web":  {"repository": f"{registry}/ontoaxis-web",  "digest": web_digest,  "commit": commit},
}
cur = None
out = []
for line in lines:
    s = line.strip()
    m = re.match(r"^- component:\s*(.+)$", s)
    if m:
        cur = m.group(1).strip()
        out.append(line)
        continue
    if cur in targets:
        replaced = False
        for field, val in targets[cur].items():
            if s.startswith(field + ":"):
                out.append(f"    {field}: {val}")
                replaced = True
                break
        if replaced:
            continue
    if s.startswith("created_at:"):
        out.append(f'created_at: "{now}"')
        continue
    if s.startswith("operator:"):
        out.append(f'operator: "{operator}"')
        continue
    out.append(line)
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"updated {path}: ontoaxis-core digest={core_digest} ontoaxis-web digest={web_digest}")
PY

log "done. digest summary:"
grep -E '^(CORE|WEB)_DIGEST=' "$OUT_DIR/digests.env"
