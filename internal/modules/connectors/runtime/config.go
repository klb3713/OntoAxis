package runtime

import (
	"encoding/json"
	"fmt"
	"math"
	"regexp"
	"sort"
	"strings"

	"github.com/google/uuid"
)

const (
	// DefaultSyncSchema is used when the connector config omits a schema.
	DefaultSyncSchema = "public"
	// identifierPattern matches safe lowercase SQL identifiers.
	identifierPattern = `^[a-z_][a-z0-9_]*$`
	// maxIdentifierLength is the Postgres identifier length limit.
	maxIdentifierLength = 63
)

var (
	identifierRegexp = regexp.MustCompile(identifierPattern)
	hostRegexp       = regexp.MustCompile(`^[A-Za-z0-9._:\[\]-]{1,255}$`)
	databaseRegexp   = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9_.-]{0,62}$`)
)

// allowedSyncConfigKeys is the strict whitelist for a postgres sync connector.
var allowedSyncConfigKeys = map[string]struct{}{
	"host":             {},
	"port":             {},
	"database":         {},
	"schema":           {},
	"tables":           {},
	"slot_name":        {},
	"publication_name": {},
	"dataset_id":       {},
}

// forbiddenSyncConfigKeys are runtime-owned keys that users must not supply.
var forbiddenSyncConfigKeys = map[string]struct{}{
	"topic_prefix": {},
	"topic.prefix": {},
	"topicprefix":  {},
}

// SyncConfig is the validated, typed whitelist view of a postgres sync config.
// secret_ref and topic naming stay outside this struct.
type SyncConfig struct {
	Host            string
	Port            int
	Database        string
	Schema          string
	Tables          []string
	SlotName        string
	PublicationName string
	DatasetID       string
}

// ParseSyncConfig validates connector config against the sync whitelist and
// returns a typed config. Unknown, forbidden, or unsafe keys are rejected and
// values are never echoed in errors.
func ParseSyncConfig(config map[string]any) (SyncConfig, error) {
	if config == nil {
		return SyncConfig{}, fmt.Errorf("%w: config must be a JSON object", ErrInvalidSyncConfig)
	}
	for key := range config {
		if _, forbidden := forbiddenSyncConfigKeys[normalizeConfigKey(key)]; forbidden {
			return SyncConfig{}, fmt.Errorf("%w: key %q is generated by the runtime and must not be supplied", ErrInvalidSyncConfig, key)
		}
		if _, allowed := allowedSyncConfigKeys[key]; !allowed {
			return SyncConfig{}, fmt.Errorf("%w: unsupported key %q", ErrInvalidSyncConfig, key)
		}
	}
	host, err := requireString(config, "host")
	if err != nil {
		return SyncConfig{}, err
	}
	if !hostRegexp.MatchString(host) {
		return SyncConfig{}, fmt.Errorf("%w: key %q is not a valid host", ErrInvalidSyncConfig, "host")
	}
	port, err := requirePort(config, "port")
	if err != nil {
		return SyncConfig{}, err
	}
	database, err := requireString(config, "database")
	if err != nil {
		return SyncConfig{}, err
	}
	if !databaseRegexp.MatchString(database) {
		return SyncConfig{}, fmt.Errorf("%w: key %q is not a valid database name", ErrInvalidSyncConfig, "database")
	}
	schema, err := optionalIdentifier(config, "schema")
	if err != nil {
		return SyncConfig{}, err
	}
	if schema == "" {
		schema = DefaultSyncSchema
	}
	tables, err := requireTables(config)
	if err != nil {
		return SyncConfig{}, err
	}
	slotName, err := optionalIdentifier(config, "slot_name")
	if err != nil {
		return SyncConfig{}, err
	}
	publicationName, err := optionalIdentifier(config, "publication_name")
	if err != nil {
		return SyncConfig{}, err
	}
	datasetID, err := requireDatasetID(config)
	if err != nil {
		return SyncConfig{}, err
	}
	return SyncConfig{
		Host:            host,
		Port:            port,
		Database:        database,
		Schema:          schema,
		Tables:          tables,
		SlotName:        slotName,
		PublicationName: publicationName,
		DatasetID:       datasetID,
	}, nil
}

func normalizeConfigKey(key string) string {
	key = strings.ToLower(strings.TrimSpace(key))
	return strings.NewReplacer("_", "", ".", "").Replace(key)
}

func requireString(config map[string]any, key string) (string, error) {
	raw, ok := config[key]
	if !ok || raw == nil {
		return "", fmt.Errorf("%w: key %q is required", ErrInvalidSyncConfig, key)
	}
	value, ok := raw.(string)
	if !ok {
		return "", fmt.Errorf("%w: key %q must be a string", ErrInvalidSyncConfig, key)
	}
	value = strings.TrimSpace(value)
	if value == "" {
		return "", fmt.Errorf("%w: key %q must not be empty", ErrInvalidSyncConfig, key)
	}
	return value, nil
}

func optionalIdentifier(config map[string]any, key string) (string, error) {
	raw, ok := config[key]
	if !ok || raw == nil {
		return "", nil
	}
	value, ok := raw.(string)
	if !ok {
		return "", fmt.Errorf("%w: key %q must be a string", ErrInvalidSyncConfig, key)
	}
	value = strings.TrimSpace(value)
	if value == "" {
		return "", fmt.Errorf("%w: key %q must not be empty when supplied", ErrInvalidSyncConfig, key)
	}
	if len(value) > maxIdentifierLength || !identifierRegexp.MatchString(value) {
		return "", fmt.Errorf("%w: key %q must match %s", ErrInvalidSyncConfig, key, identifierPattern)
	}
	return value, nil
}

func requirePort(config map[string]any, key string) (int, error) {
	raw, ok := config[key]
	if !ok || raw == nil {
		return 0, fmt.Errorf("%w: key %q is required", ErrInvalidSyncConfig, key)
	}
	var port int
	switch value := raw.(type) {
	case int:
		port = value
	case int32:
		port = int(value)
	case int64:
		port = int(value)
	case float32:
		port = floatToPort(float64(value))
		if float64(port) != float64(value) {
			return 0, fmt.Errorf("%w: key %q must be an integer", ErrInvalidSyncConfig, key)
		}
	case float64:
		if value != math.Trunc(value) {
			return 0, fmt.Errorf("%w: key %q must be an integer", ErrInvalidSyncConfig, key)
		}
		port = int(value)
	case json.Number:
		parsed, err := value.Int64()
		if err != nil {
			return 0, fmt.Errorf("%w: key %q must be an integer", ErrInvalidSyncConfig, key)
		}
		port = int(parsed)
	default:
		return 0, fmt.Errorf("%w: key %q must be an integer", ErrInvalidSyncConfig, key)
	}
	if port < 1 || port > 65535 {
		return 0, fmt.Errorf("%w: key %q must be between 1 and 65535", ErrInvalidSyncConfig, key)
	}
	return port, nil
}

func floatToPort(value float64) int {
	if value != math.Trunc(value) || value < math.MinInt32 || value > math.MaxInt32 {
		return -1
	}
	return int(value)
}

func requireTables(config map[string]any) ([]string, error) {
	raw, ok := config["tables"]
	if !ok || raw == nil {
		return nil, fmt.Errorf("%w: key %q is required", ErrInvalidSyncConfig, "tables")
	}
	var values []string
	switch typed := raw.(type) {
	case []string:
		values = append(values, typed...)
	case []any:
		for _, item := range typed {
			value, ok := item.(string)
			if !ok {
				return nil, fmt.Errorf("%w: key %q must be an array of strings", ErrInvalidSyncConfig, "tables")
			}
			values = append(values, value)
		}
	default:
		return nil, fmt.Errorf("%w: key %q must be an array of strings", ErrInvalidSyncConfig, "tables")
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("%w: key %q must not be empty", ErrInvalidSyncConfig, "tables")
	}
	seen := make(map[string]struct{}, len(values))
	tables := make([]string, 0, len(values))
	for _, value := range values {
		table := strings.TrimSpace(value)
		if len(table) > maxIdentifierLength || !identifierRegexp.MatchString(table) {
			return nil, fmt.Errorf("%w: table %q must match %s", ErrInvalidSyncConfig, table, identifierPattern)
		}
		if _, duplicate := seen[table]; duplicate {
			continue
		}
		seen[table] = struct{}{}
		tables = append(tables, table)
	}
	sort.Strings(tables)
	return tables, nil
}

func requireDatasetID(config map[string]any) (string, error) {
	value, err := requireString(config, "dataset_id")
	if err != nil {
		return "", err
	}
	parsed, err := uuid.Parse(value)
	if err != nil {
		return "", fmt.Errorf("%w: key %q must be a uuid", ErrInvalidSyncConfig, "dataset_id")
	}
	return parsed.String(), nil
}
