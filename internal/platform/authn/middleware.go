func bearerToken(r *http.Request) (string, bool) {
	if r == nil {
		return "", false
	}
	raw := strings.TrimSpace(r.Header.Get("Authorization"))
	if raw == "" {
		return "", false
	}
	parts := strings.Fields(raw)
	if len(parts) != 2 || !strings.EqualFold(parts[0], "Bearer") || parts[1] == "" {
		return "", false
	}
	return parts[1], true
}

func headerPresent(r *http.Request, names ...string) bool {
	if r == nil {
		return false
	}
	for _, name := range names {
		if len(r.Header.Values(name)) > 0 {
			return true
		}
	}
	return false
}

func splitHeaderList(raw string) []string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return nil
	}
	parts := strings.Split(raw, ",")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		value := strings.TrimSpace(part)
		if value != "" {
			out = append(out, value)
		}
	}
	return out
}

func requestIDFromContext(ctx context.Context) string {
	if ctx == nil {
		return ""
	}
	return observability.RequestID(ctx)
}

// requestWithResolvedID mirrors header/traceparent request IDs into the
// context so Authenticate and TenantContext observe the same correlation ID
// that error responses use.
func requestWithResolvedID(r *http.Request) *http.Request {
	if r == nil || requestIDFromContext(r.Context()) != "" {
		return r
	}
	if id := requestIDFromRequest(r); id != "" {
		return r.WithContext(observability.WithRequestID(r.Context(), id))
	}
	return r
}

// requestIDFromRequest resolves a correlation ID from the request context
// first, then X-Request-Id, then W3C traceparent. It never invents an ID, so
// tests can distinguish "not supplied" from "generated by the HTTP server".
func requestIDFromRequest(r *http.Request) string {
	if r == nil {
		return ""
	}
	if id := requestIDFromContext(r.Context()); id != "" {
		return id
	}
	if id := strings.TrimSpace(r.Header.Get("X-Request-Id")); id != "" {
		return id
	}
	return traceIDFromTraceparent(r.Header.Get("traceparent"))
}

func traceIDFromTraceparent(value string) string {
	parts := strings.Split(strings.TrimSpace(value), "-")
	if len(parts) != 4 {
		return ""
	}
	if len(parts[1]) != 32 || !isHex(parts[1]) || strings.Trim(parts[1], "0") == "" {
		return ""
	}
	if len(parts[2]) != 16 || !isHex(parts[2]) {
		return ""
	}
	if len(parts[3]) != 2 || !isHex(parts[3]) {
		return ""
	}
	return parts[1]
}

func isHex(value string) bool {
	for _, r := range value {
		if (r < '0' || r > '9') && (r < 'a' || r > 'f') && (r < 'A' || r > 'F') {
			return false
		}
	}
	return true
}

func errorsIsPermission(err error) bool {
	return errors.Is(err, ErrPermissionDenied)
}
